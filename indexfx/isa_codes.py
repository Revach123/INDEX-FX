def parse_otc_name(name: str) -> dict | None:
    """S_/F_ לפי נספח א'. מחזיר None אם לא בפורמט."""
    p = str(name or "").split("_")
    if len(p) < 8 or p[0] not in ("S", "F", "SPOT"):
        return None
    out = {"kind": p[0], "start": p[1], "term_days": p[2], "reset_days": p[3], "settle": p[4], "settle_lag": p[5],
           "csa": p[6], "calc_agent": p[7]}
    if p[0] == "S" and len(p) >= 10:
        out["anchor_rate"] = ANCHOR_RATE.get(int(p[8]) if p[8].isdigit() else -1, p[8])
        out["anchor_period"] = ANCHOR_PERIOD.get(int(p[9]) if p[9].isdigit() else -1, p[9])
    return out
